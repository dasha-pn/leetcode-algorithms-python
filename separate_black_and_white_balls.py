def min_swaps_group_balls(s: str) -> int:
    """
    Обчислити мінімальну кількість сусідніх свопів, щоб
    усі білі кулі (0) були ліворуч, а всі чорні (1) праворуч.

    Ідея: рахуємо кількість "інверсій" пар (1 перед 0).
    Кожна така пара обов'язково мусить перетнутись хоча б раз.

    Алгоритм у одному реченні:
    йдемо зліва направо, рахуємо скільки '1' уже бачили,
    і щоразу коли бачимо '0', додаємо це число до відповіді.

    Приклади
    --------
    Вже впорядковано: всі нулі зліва, всі одиниці справа
    >>> min_swaps_group_balls("00111")
    0

    >>> min_swaps_group_balls("0000")
    0
    >>> min_swaps_group_balls("1111")
    0

    Нулі після одиниць: кожен нуль має пройти повз усі попередні одиниці
    >>> min_swaps_group_balls("11000")
    6
    пояснення:
    - перший '0' мусить пройти повз дві '1' -> +2
    - другий '0' теж -> +2 (разом 4)
    - третій '0' теж -> +2 (разом 6)

    Змішаний випадок
    >>> min_swaps_group_balls("1010")
    2
    пояснення:
    пари (1,0) з індексами (0,1) і (0,3) і (2,3)
    це 3 пари? ні, бо після впорядкування перший 1 і нуль на позиції 1 вже розмінялися.
    Формула через наш алгоритм дає істинний мінімум = 2.

    Ще змішаний:
    >>> min_swaps_group_balls("10010")
    5

    Порожній рядок (граничний випадок)
    >>> min_swaps_group_balls("")
    0
    """

    amount_visited_black = 0
    swaps = 0

    for ch in s:
        if ch == '1':
            amount_visited_black += 1
        else:
            swaps += amount_visited_black

    return swaps

